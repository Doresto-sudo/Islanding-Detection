def compute_thd(coeffs):
    x = np.asarray(coeffs, dtype=float)
    if len(x) < 2:
        return 0.0
    fft_vals = np.abs(np.fft.rfft(x))
    if len(fft_vals) < 2 or fft_vals[1] < 1e-10:
        return 0.0
    fundamental = fft_vals[1]
    harmonics   = fft_vals[2:]
    return float(np.sqrt(np.sum(harmonics ** 2)) / fundamental)


def compute_sinad(coeffs):
    x = np.asarray(coeffs, dtype=float)
    if len(x) < 2:
        return 0.0
    fft_vals     = np.abs(np.fft.rfft(x))
    total_power  = np.sum(fft_vals ** 2)
    if total_power < 1e-10:
        return 0.0
    fund_idx     = np.argmax(fft_vals[1:]) + 1
    signal_power = fft_vals[fund_idx] ** 2
    noise_power  = total_power - signal_power
    if noise_power < 1e-10:
        return float(signal_power / 1e-10)
    return float(signal_power / noise_power)


def extract_band_features(coeffs):
    x        = np.asarray(coeffs, dtype=float)
    xabs     = np.abs(x)
    eps      = 1e-10
    mean_val = float(np.mean(x))
    std_val  = float(np.std(x))
    rms_val  = float(np.sqrt(np.mean(x ** 2)))
    peak_val = float(np.max(xabs))
    mean_abs  = float(np.mean(xabs))
    mean_sqrt = float(np.mean(np.sqrt(xabs))) ** 2
    crest_factor     = peak_val / (rms_val   + eps)
    impulse_factor   = peak_val / (mean_abs  + eps)
    shape_factor     = rms_val  / (mean_abs  + eps)
    clearance_factor = peak_val / (mean_sqrt + eps)
    if std_val > eps:
        z        = (x - mean_val) / std_val
        kurtosis = float(np.mean(z ** 4))
        skewness = float(np.mean(z ** 3))
    else:
        kurtosis = 0.0
        skewness = 0.0
    thd   = compute_thd(x)
    sinad = compute_sinad(x)
    return [
        mean_val, std_val, rms_val, peak_val,
        crest_factor, impulse_factor, shape_factor, clearance_factor,
        kurtosis, skewness, thd, sinad
    ]


def extract_cycle_features(cycle):
    features = []
    for phase_idx in range(N_PHASES):
        signal = cycle[phase_idx, :]
        coeffs = pywt.wavedec(signal, WAVELET, level=DWT_LEVEL)
        for band_coeffs in coeffs:
            features.extend(extract_band_features(band_coeffs))
    return features


def extract_features_from_cycles(cycles, set_name):
    n        = len(cycles)
    features = np.zeros((n, N_FEATURES), dtype=np.float32)
    every    = max(1, n // 10)
    print('  Extracting from ' + set_name + ' (' + str(n) + ' cycles)...')
    for i in range(n):
        features[i, :] = extract_cycle_features(cycles[i])
        if (i + 1) % every == 0 or (i + 1) == n:
            print('    ' + str(i + 1) + '/' + str(n) +
                  '  (' + str(round(100 * (i + 1) / n, 1)) + '%)')
    print('  Done -> shape: ' + str(features.shape))
    return features


