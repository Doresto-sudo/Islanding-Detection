"""**#  PHASE C - DOWNSAMPLING + DWT FEATURE EXTRACTION**

**Step 1**: Downsample class 0 in training cycles ONLY to match class 1 size before DWT extraction

**Step 2**: DWT feature extraction
- Wavelet : Sym4
- Level   : 2  (reduced from 3 due to 64-sample window)
- Bands   : cA2 (0-480Hz)   -> 16 coefficients
- cD2 (480-960Hz) -> 16 coefficients
- cD1 (960-1920Hz)-> 32 coefficients
- Stats   : 12 per band per phase
- Total   : 3 phases x 3 bands x 12 stats = 108 features


**WHY LEVEL 2 INSTEAD OF LEVEL 3:**
- At Level 3 with 64-sample windows, cA3 and cD3 only have 8 coefficients each — too few for reliable
- kurtosis, THD and SINAD estimation.
- Level 2 gives 16 coefficients minimum per band, making all 12 statistics statistically meaningful.

**Step 3**: Spearman feature selection (|rho| > 0.1)

**Step 4**: StandardScaler
- Fit on balanced training set only
- Transform all three sets

"""

import numpy as np
import pywt
from sklearn.preprocessing import StandardScaler
WAVELET    = 'sym4'
DWT_LEVEL  = 2
N_PHASES   = 3
