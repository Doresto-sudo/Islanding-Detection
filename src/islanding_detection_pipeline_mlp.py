# -- WINDOWING FUNCTION -------------------------------------------
def slice_recordings_into_cycles(recordings, event_classes, split_name):
    """
    Slices each full 2881-sample recording into 64-sample cycles
    and assigns the correct class label to each cycle.

    Parameters:
        recordings    : array of 2881x4 recordings
        event_classes : array of post-event class labels
                        (one per recording, from Phase A)
        split_name    : string label for printing ('Training' etc.)

    Returns:
        cycles : np.array of shape (N, 3, 64)
                 N = total cycles across all recordings
                 3 = three phases (Va, Vb, Vc)
                 64 = samples per cycle

        labels : np.array of shape (N,)
                 class label for each cycle (0, 1, or 2)

    Cycle assignment:
        cycle_idx < EVENT_CYCLE - 1  -> class 0 (pre-event, normal)
        cycle_idx >= EVENT_CYCLE - 1 -> post_class (post-event)
        No cycle is discarded — cycle 30 (0-indexed: 29) is clean.
    """

    all_cycles = []
    all_labels = []

    n_recordings = len(recordings)

    for rec_idx in range(n_recordings):

        recording  = recordings[rec_idx]     # shape: (2881, 4)
        post_class = event_classes[rec_idx]  # class for post-event cycles

        # Extract three phase voltages (skip column 0 = time)
        Va = recording[:, 1]
        Vb = recording[:, 2]
        Vc = recording[:, 3]

        # Total number of complete 64-sample cycles
        n_cycles = len(Va) // WINDOW_SIZE    # = 45 cycles

        for cycle_idx in range(n_cycles):

            # -- Extract 64-sample window -------------------------
            start = cycle_idx * WINDOW_SIZE
            end   = start + WINDOW_SIZE

            window_Va = Va[start:end]   # shape: (64,)
            window_Vb = Vb[start:end]   # shape: (64,)
            window_Vc = Vc[start:end]   # shape: (64,)

            # Stack three phases -> shape: (3, 64)
            window = np.stack([window_Va, window_Vb, window_Vc], axis=0)

            # -- Assign label -------------------------------------
            # EVENT_CYCLE - 1 = 29 (0-indexed) = cycle 30 (1-indexed)
            # Cycles 0-28 (0-indexed) = pre-event  -> class 0
            # Cycles 29-44 (0-indexed) = post-event -> post_class
            if cycle_idx < EVENT_CYCLE - 1:
                label = 0            # pre-event -> class 0 (non-islanding)
            else:
                label = post_class   # post-event -> class from Phase A

            all_cycles.append(window)
            all_labels.append(label)

    cycles = np.array(all_cycles, dtype=np.float32)   # (N, 3, 64)
    labels = np.array(all_labels, dtype=np.int32)      # (N,)

    return cycles, labels


